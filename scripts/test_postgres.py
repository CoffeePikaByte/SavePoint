"""Own one local, disposable Compose project; never read application DB settings."""
import json
import os
from pathlib import Path
import secrets
import shutil
import signal
import subprocess
import sys
import tempfile
import time
import uuid

POSTGRES_IMAGE = "postgres:16@sha256:95206741a5b214807675e14165369d05b93a9cf692223b616d07cca227e74b0b"


def validate_environment(env):
    if env.get("SAVEPOINT_POSTGRES_TESTS") != "1":
        raise RuntimeError("Explicit SAVEPOINT_POSTGRES_TESTS=1 is required.")
    if any(env.get(key) for key in ("SAVEPOINT_TEST_CONNECTION", "SAVEPOINT_TEST_RUN_ID", "SAVEPOINT_TEST_TOKEN")):
        raise RuntimeError("Connection and ownership values must be generated by this script, not supplied by the caller.")
    if env.get("DOCKER_HOST", "unix:///var/run/docker.sock") != "unix:///var/run/docker.sock":
        raise RuntimeError("Only the local unix:///var/run/docker.sock endpoint is authorized.")
    if env.get("DOCKER_CONTEXT", "default") != "default" or env.get("DOCKER_TLS_VERIFY") or env.get("DOCKER_CERT_PATH"):
        raise RuntimeError("Remote or TLS Docker configuration is not authorized.")


def verify_labels(labels, project, run):
    if labels.get("com.docker.compose.project") != project or labels.get("io.savepoint.integration.run") != run:
        raise RuntimeError("Resource identity mismatch; refusing to operate on it.")


def group_alive(pgid):
    try:
        os.killpg(pgid, 0)
        return True
    except ProcessLookupError:
        return False


def wait_group_exit(pgid, timeout):
    deadline = time.monotonic() + timeout
    while group_alive(pgid):
        if time.monotonic() >= deadline:
            return False
        time.sleep(0.05)
    return True


def stop_test_group(process):
    # The group is created exclusively by Popen(start_new_session=True).
    # The leader exiting does not prove that its testhost children have exited.
    if group_alive(process.pid):
        try:
            os.killpg(process.pid, signal.SIGTERM)
        except ProcessLookupError:
            pass
    try:
        process.wait(timeout=1)  # Reap the leader, without using it as the group-liveness signal.
    except subprocess.TimeoutExpired:
        pass
    if not wait_group_exit(process.pid, 10):
        try:
            os.killpg(process.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
        process.wait(timeout=5)
        if not wait_group_exit(process.pid, 5):
            raise RuntimeError("The owned test process group has not fully exited; cleanup cannot be confirmed.")


def run_tests(args, env, root):
    process = subprocess.Popen(args, env=env, cwd=root, start_new_session=True)
    try:
        result = process.wait(timeout=300)
        if not wait_group_exit(process.pid, 2):
            raise RuntimeError("The test driver exited with surviving child processes.")
        return result
    except BaseException:
        stop_test_group(process)
        raise RuntimeError("Test process interrupted or exceeded its deadline; its owned process group was stopped.")


def main():
    validate_environment(os.environ)
    root = Path(__file__).resolve().parents[1]
    run_id = uuid.uuid4().hex
    project = "spit_" + run_id
    password, token = secrets.token_hex(32), secrets.token_hex(32)
    temporary = Path(tempfile.mkdtemp(prefix="savepoint-postgres-"))
    os.chmod(temporary, 0o700)
    docker_config = temporary / "docker-config"
    docker_config.mkdir()
    # Do not reuse registry credentials, contexts, .env files or Compose overrides.
    env = {key: value for key, value in os.environ.items()
           if not key.startswith(("DOCKER_", "COMPOSE_", "SAVEPOINT_TEST_"))}
    env.update(SAVEPOINT_TEST_RUN_ID=run_id, SAVEPOINT_TEST_PASSWORD=password)
    env.update(MSBUILDDISABLENODEREUSE="1", DOTNET_CLI_DO_NOT_USE_MSBUILD_SERVER="1")
    env_file = temporary / "compose.env"
    env_file.write_text("")
    docker = ["docker", "--config", str(docker_config), "--host", "unix:///var/run/docker.sock"]
    compose = docker + ["compose", "--env-file", str(env_file), "-f", str(root / "docker-compose.integration.yml"), "-p", project]
    started = False
    pulled_image = False
    image_id = None

    def execute(args, *, capture=False, data=None, timeout=180, check=True):
        return subprocess.run(args, env=env, cwd=root, text=True, input=data,
                              stdout=subprocess.PIPE if capture else None,
                              stderr=subprocess.PIPE if capture else None,
                              timeout=timeout, check=check)

    def inventory():
        result = {}
        for kind, args in (("container", ["ps", "-aq"]), ("network", ["network", "ls", "-q"]),
                           ("volume", ["volume", "ls", "-q"])):
            result[kind] = execute(docker + args + ["--filter", "label=com.docker.compose.project=" + project], capture=True).stdout.split()
        return result

    def verify_resources(resources):
        if resources["volume"]:
            raise RuntimeError("Unexpected volume in tmpfs-only test project; refusing cleanup.")
        for kind in ("container", "network"):
            for identity in resources[kind]:
                item = json.loads(execute(docker + [kind, "inspect", identity], capture=True).stdout)[0]
                labels = item["Config"]["Labels"] if kind == "container" else item["Labels"]
                verify_labels(labels or {}, project, run_id)
                if kind == "container":
                    if labels.get("com.docker.compose.service") != "postgres":
                        raise RuntimeError("Unexpected service in test project.")
                    if any(mount["Type"] in ("bind", "volume") for mount in item["Mounts"]):
                        raise RuntimeError("Test container unexpectedly mounts persistent storage.")

    def interrupt(signum, _frame):
        raise RuntimeError("Integration run interrupted; scoped cleanup will run.")

    previous = {sig: signal.signal(sig, interrupt) for sig in (signal.SIGINT, signal.SIGTERM)}
    try:
        execute(docker + ["info", "--format", "{{.ServerVersion}}"], capture=True)
        if any(inventory().values()):
            raise RuntimeError("Generated project unexpectedly exists; no resources will be changed.")
        cached = execute(docker + ["image", "inspect", POSTGRES_IMAGE, "--format", "{{.Id}}"], capture=True, check=False)
        if cached.returncode != 0:
            # Pull by immutable digest, never refresh a pre-existing mutable image tag.
            execute(docker + ["pull", POSTGRES_IMAGE], timeout=300)
            pulled_image = True
        image_id = execute(docker + ["image", "inspect", POSTGRES_IMAGE, "--format", "{{.Id}}"], capture=True).stdout.strip()
        print(f"Integration project: {project}; PostgreSQL image: {POSTGRES_IMAGE}", flush=True)
        started = True  # Also clean partially created resources if compose up fails.
        execute(compose + ["up", "-d", "--pull", "never", "--wait", "--wait-timeout", "90"], timeout=150)
        resources = inventory()
        verify_resources(resources)
        if len(resources["container"]) != 1 or len(resources["network"]) != 1:
            raise RuntimeError("Unexpected resource count in owned integration project.")
        container = resources["container"][0]
        mapping = execute(compose + ["port", "postgres", "5432"], capture=True).stdout.strip()
        host, port = mapping.rsplit(":", 1)
        if host != "127.0.0.1" or not port.isdigit() or int(port) < 1024 or int(port) == 5433:
            raise RuntimeError("Unexpected test port binding.")
        database = "spit_" + run_id
        bootstrap = ("CREATE TABLE public.test_run_identity (run_id text PRIMARY KEY, token text NOT NULL);\n"
                     f"INSERT INTO public.test_run_identity VALUES ('{run_id}', '{token}');\n")
        execute(docker + ["exec", "-i", container, "psql", "-U", "spit_admin", "-d", database,
                          "--set", "ON_ERROR_STOP=1"], data=bootstrap, capture=True)
        env.update(SAVEPOINT_POSTGRES_TESTS="1", SAVEPOINT_TEST_TOKEN=token,
                   SAVEPOINT_TEST_CONNECTION=f"Host=127.0.0.1;Port={port};Database={database};Username=spit_admin;Password={password};Pooling=false")
        result = run_tests(["dotnet", "test", str(root / "GameHub.Infrastructure.IntegrationTests/GameHub.Infrastructure.IntegrationTests.csproj"),
                          "--artifacts-path", str(temporary / "artifacts"), "-p:NuGetAudit=false",
                          "--disable-build-servers", "-p:UseSharedCompilation=false",
                          "--logger", "console;verbosity=normal"], env, root)
        # Test fixture cleanup must leave no per-test database, even if individual tests failed.
        leftover = execute(docker + ["exec", "-i", container, "psql", "-U", "spit_admin", "-d", database,
                                    "--set", "ON_ERROR_STOP=1", "-At"],
                           data=f"SELECT datname FROM pg_database WHERE datname LIKE 'spit_%' AND datname <> '{database}';\n", capture=True).stdout.strip()
        if leftover:
            raise RuntimeError("Per-test database cleanup failed; owned container will still be destroyed.")
        print("Per-test databases removed: verified.", flush=True)
        return result
    finally:
        try:
            if started:
                # Only this run's marked resources can be stopped or removed.
                resources = inventory()
                verify_resources(resources)
                execute(compose + ["down", "--volumes", "--remove-orphans"], timeout=90)
                if any(inventory().values()):
                    raise RuntimeError("Compose resources remain after scoped cleanup.")
                print("Owned containers, networks and volumes removed: verified.", flush=True)
            if pulled_image:
                current = execute(docker + ["image", "inspect", POSTGRES_IMAGE, "--format", "{{.Id}}"], capture=True).stdout.strip()
                if current != image_id or execute(docker + ["ps", "-aq", "--filter", "ancestor=" + image_id], capture=True).stdout.strip():
                    raise RuntimeError("New image identity or usage changed; refusing image cleanup.")
                execute(docker + ["image", "rm", POSTGRES_IMAGE])
                if execute(docker + ["image", "inspect", POSTGRES_IMAGE], capture=True, check=False).returncode == 0:
                    raise RuntimeError("New image reference remains after cleanup.")
                print("New image reference removed: verified.", flush=True)
        except Exception:
            print(f"Cleanup requires inspection of project {project}; no global cleanup was attempted.", file=sys.stderr)
            raise
        finally:
            for sig, handler in previous.items():
                signal.signal(sig, handler)
            shutil.rmtree(temporary)
            print("Temporary files removed: verified.", flush=True)


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception as error:
        # Never print connection strings, subprocess environments or credentials.
        print(f"Integration runner failed safely: {type(error).__name__}. {str(error) if isinstance(error, RuntimeError) else 'See the preceding operation output.'}", file=sys.stderr)
        sys.exit(1)
